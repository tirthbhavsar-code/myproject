# 1. Integer
age = 25
print("Integer:", age)
print(type(age))

# 2. Float
price = 99.50
print("\nFloat:", price)
print(type(price))

# 3. String
name = "Tirth"
print("\nString:", name)
print(type(name))

# 4. Boolean
is_login = True
print("\nBoolean:", is_login)
print(type(is_login))

# 5. List
fruits = ["apple", "banana", "mango"]
print("\nList:", fruits)
print(type(fruits))

# 6. Tuple
numbers = (10, 20, 30)
print("\nTuple:", numbers)
print(type(numbers))

# 7. Dictionary
student = {
    "name": "Tirth",
    "age": 25,
    "city": "Ahmedabad"
}
print("\nDictionary:", student)
print(type(student))

